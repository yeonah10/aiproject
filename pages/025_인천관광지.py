st.sidebar.header("🔎 관광지 찾기")

day_filter = st.sidebar.selectbox(
    "여행 날짜",
    ["전체", "1일 차", "2일 차"]
)

category_filter = st.sidebar.selectbox(
    "관광 유형",
    ["전체"] + sorted(df["유형"].unique().tolist())
)

keyword = st.sidebar.text_input("관광지 이름 검색")

filtered_df = df.copy()

if day_filter != "전체":
    filtered_df = filtered_df[
        filtered_df["일차"] == day_filter
    ]

if category_filter != "전체":
    filtered_df = filtered_df[
        filtered_df["유형"] == category_filter
    ]

if keyword.strip():
    filtered_df = filtered_df[
        filtered_df["관광지"].str.contains(
            keyword.strip(),
            case=False,
            na=False
        )
    ]


